# generate_bsp.py

import vitis
import os
import shutil

# ---- Names
proj_name      = os.environ.get("PROJECT")

proj_root      = os.environ.get("PROJECT_ROOT")
build_dir      = f"{proj_root}/build/{proj_name}"
xsa_path       = f"{build_dir}/{proj_name}.xsa"
workspace_path = f"{build_dir}/{proj_name}.vitis"
# What the Microblaze app builds need (BSP, linker script, ISA flags), read by
# scripts/bootstrap/Makefile.microblaze
bsp_mk_path    = f"{build_dir}/bsp.mk"

platform_name  = f"{proj_name}_platform"
app_name       = f"{proj_name}_app"

# Instance names in the block design of the Microblaze and of the UART used
# for stdin/stdout (empty means default)
mb_cpu         = os.environ.get("MB_CPU") or "microblaze_riscv_0"
mb_uart        = os.environ.get("MB_UART") or "axi_uartlite_0"
domain_name    = f"standalone_{mb_cpu}"

# ---- Client setup
client = vitis.create_client()

# Delete the workspace if already exists, and bsp.mk that points into it.
if os.path.exists(bsp_mk_path):
    os.remove(bsp_mk_path)
if (os.path.isdir(workspace_path)):
    shutil.rmtree(workspace_path)

client.set_workspace(workspace_path)

print(xsa_path)

# ---- Platform creation
platform = client.create_platform_component(
    name=platform_name,
    hw_design=os.path.abspath(xsa_path),
    os="standalone",
    cpu=mb_cpu,
    no_boot_bsp=True
)

domain = platform.get_domain(domain_name)

domain.set_config(
    option="os",
    param="standalone_stdout",
    value=mb_uart
)

domain.set_config(
    option="os",
    param="standalone_stdin",
    value=mb_uart
)

platform.build()

# Note: The FSBL is already handled by the Zynq part, see xsct/generate_boot.tcl for more info.
#       This generates the headers and libraries.

# ---- Application component

platform_xpfm = client.find_platform_in_repos(platform_name)

app = client.create_app_component(
    name=app_name,
    platform=platform_xpfm,
    domain=domain_name,
    template="hello_world"
)

app.build()

# Note: This is used ONLY to generate linker script

# ---- bsp.mk
# Vitis gives the platform location and the linker script, but not the BSP
# directory: it is <platform>/<cpu>/<domain>/bsp (Vitis 2024.2), checked below
# so that a layout change fails here rather than in the app builds.
bsp_dir = os.path.join(domain.platform_location, mb_cpu, domain_name, "bsp")
lscript = app.get_ld_script().file_path
cflags_yaml = os.path.join(bsp_dir, "cflags.yaml")

for path in [os.path.join(bsp_dir, "include", "xparameters.h"),
             os.path.join(bsp_dir, "lib", "libxil.a"),
             os.path.join(bsp_dir, "Xilinx.spec"),
             cflags_yaml,
             lscript]:
    if not os.path.isfile(path):
        raise SystemExit(f"error: {path} not found, did the Vitis workspace layout change?")

# -march/-mabi of the CPU, from the "cflags: ..." line
arch_flags = ""
with open(cflags_yaml) as f:
    for line in f:
        if line.startswith("cflags:"):
            arch_flags = line.split(":", 1)[1].strip()
if not arch_flags:
    raise SystemExit(f"error: no cflags in {cflags_yaml}")

with open(bsp_mk_path + ".tmp", "w") as f:
    f.write(f"# Generated by scripts/vitis/generate_bsp.py for {proj_name}, do not edit\n")
    f.write(f"MB_CPU        := {mb_cpu}\n")
    f.write(f"BSP_DIR       := {os.path.abspath(bsp_dir)}\n")
    f.write(f"BSP_LSCRIPT   := {os.path.abspath(lscript)}\n")
    f.write(f"MB_ARCH_FLAGS ?= {arch_flags}\n")
os.replace(bsp_mk_path + ".tmp", bsp_mk_path)
print(f"wrote {bsp_mk_path}")

# ---- Cleanup
vitis.dispose()